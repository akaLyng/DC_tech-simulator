import { L, NEED_ROOT, pingOut, parsePing } from './helpers.js';

// Ported from the original browser practice lab (INC-1042). Hostname, addresses and the old/new
// DNS servers are randomized per shift; commands, outputs and step logic are the lab's.
export default {
  key: 'dns',
  kind: 'console',
  priority: 'P3',
  params: (r) => {
    const net = r.subnet();
    let oldDns = r.int(60, 120);
    let newDns = r.int(30, 59);
    return { host: r.host('app'), net, ip: `${net}.${r.octet()}`, oldDns: `${net}.${oldDns}`, newDns: `${net}.${newDns}` };
  },
  build: (p) => ({
    id: p.id, host: p.host, user: "tech", cwd: "~", name: `${p.host} can't find anything`, topic: "DNS, resolv.conf",
    location: { rack: p.rack, u: p.u, size: 2 }, priority: "P3",
    help: "ping -c 3 <ip|name>, cat /etc/resolv.conf, dig <name>, echo \"nameserver X\" | sudo tee /etc/resolv.conf, sudo apt update",
    brief: `"apt update" on ${p.host} fails with "Temporary failure resolving". The network team says the network is fine. Network team note from last week: the old DNS server ${p.oldDns} was retired, the new one is ${p.newDns}.`,
    files: [],
    init: () => ({ dns: p.oldDns }),
    exec(c, st, sudo, ev) {
      const dnsOk = () => [p.newDns, "1.1.1.1", "8.8.8.8"].includes(st.dns);
      if (/^ip (a|addr)( show)?( eth0)?$/.test(c)) return L(`2: eth0: <BROADCAST,MULTICAST,UP,LOWER_UP> mtu 1500 state UP\n    inet ${p.ip}/24 brd ${p.net}.255 scope global eth0`);
      if (/^ip (r|route)( show)?$/.test(c)) return L(`default via ${p.net}.1 dev eth0\n${p.net}.0/24 dev eth0 proto kernel scope link src ${p.ip}`);
      if (/^cat \/etc\/resolv\.conf$/.test(c)) { ev.add("catResolv"); return L(`# Generated by the provisioning script\nnameserver ${st.dns}`); }
      const echoTee = c.match(/^echo ["']?nameserver (\S+?)["']? \| sudo tee \/etc\/resolv\.conf$/);
      if (echoTee) { st.dns = echoTee[1]; ev.add("wrote"); return L(`nameserver ${st.dns}`); }
      if (/^echo ["']?nameserver \S+["']? \| tee \/etc\/resolv\.conf$/.test(c)) return L("tee: /etc/resolv.conf: Permission denied", "o-err").concat(L("The file belongs to root. Put sudo in front of tee: ... | sudo tee /etc/resolv.conf", "o-dim"));
      if (/^(sudo )?echo .*> ?\/etc\/resolv\.conf$/.test(c)) return L("bash: /etc/resolv.conf: Permission denied", "o-err").concat(L("Classic trap: the > redirect is done by your own shell, not by sudo. That's why people pipe into sudo tee instead.", "o-dim"));
      if (/^(nano|vi|vim) /.test(c)) return L(`Editors don't run in this lab. Use: echo "nameserver ${p.newDns}" | sudo tee /etc/resolv.conf`, "o-dim");
      const dig = c.match(/^(dig|nslookup|host)\s+(\S+)$/);
      if (dig) {
        ev.add("dig");
        if (!dnsOk()) return L(`;; communications error to ${st.dns}#53: timed out\n;; communications error to ${st.dns}#53: timed out\n;; no servers could be reached`, "o-err");
        ev.add("nameOk");
        return L(`;; ANSWER SECTION:\n${dig[2]}.\t\t300\tIN\tA\t142.250.74.46\n\n;; SERVER: ${st.dns}#53(${st.dns})\n;; Query time: 9 msec`);
      }
      const ping = parsePing(c);
      if (ping) {
        if (/^\d+\.\d+\.\d+\.\d+$/.test(ping.target)) {
          if (ping.target === p.oldDns) { ev.add("ping99"); return pingOut(ping.target, ping.target, false, ping.count, ping.note); }
          if (["8.8.8.8", "1.1.1.1", `${p.net}.1`, p.newDns].includes(ping.target)) { ev.add("pingIp"); return pingOut(ping.target, ping.target, true, ping.count, ping.note); }
          return pingOut(ping.target, ping.target, false, ping.count, ping.note);
        }
        ev.add("pingName");
        if (!dnsOk()) return L(`ping: ${ping.target}: Temporary failure in name resolution`, "o-err");
        ev.add("nameOk");
        return pingOut(ping.target, "142.250.74.46", true, ping.count, ping.note);
      }
      if (/^apt(-get)? update$/.test(c)) {
        if (!sudo) return NEED_ROOT("apt update");
        if (!dnsOk()) return L("Err:1 http://archive.ubuntu.com/ubuntu noble InRelease\n  Temporary failure resolving 'archive.ubuntu.com'\nW: Some index files failed to download.", "o-err");
        ev.add("aptOk"); return L("Hit:1 http://archive.ubuntu.com/ubuntu noble InRelease\nGet:2 http://security.ubuntu.com/ubuntu noble-security InRelease [126 kB]\nReading package lists... Done");
      }
      return null;
    },
    steps: [
      {
        title: "Split the problem: numbers or names?",
        body: "<p>The fastest DNS test there is: ping an <b>IP address</b>, then ping a <b>name</b>.</p><p>If the IP works but the name fails, cables, IP, gateway and routing are all fine. Only the name lookup is broken.</p>",
        try: ["ping -c 3 8.8.8.8", "ping -c 3 google.com"], done: (st, ev) => ev.has("pingIp") && ev.has("pingName"),
        learned: "<p>8.8.8.8 answered, <code>google.com</code> gave <b>Temporary failure in name resolution</b>. You've just ruled out the whole network in two commands. It's DNS.</p>"
      },
      {
        title: "Which DNS server is it asking?",
        body: "<p>Linux keeps its DNS servers in <code>/etc/resolv.conf</code>. <code>cat</code> prints a file. <code>dig</code> asks DNS directly and shows which server answered, or didn't.</p>",
        try: ["cat /etc/resolv.conf", "dig google.com"], done: (st, ev) => ev.has("catResolv"),
        learned: `<p>The server is still pointed at <code>${p.oldDns}</code>. The ticket says that one was retired last week. Someone changed the network but not this server's config.</p>`
      },
      {
        title: "Confirm the old server is really gone",
        body: "<p>Don't trust notes blindly. Check it yourself.</p>",
        try: [`ping -c 3 ${p.oldDns}`], done: (st, ev) => ev.has("ping99"),
        learned: `<p>100% packet loss. Nothing lives at ${p.oldDns} any more, so every lookup times out.</p>`
      },
      {
        title: "Point it at the new server",
        body: "<p>You need to overwrite a file that root owns. The obvious <code>sudo echo ... &gt; /etc/resolv.conf</code> fails, because the <code>&gt;</code> is run by your own shell, not by sudo.</p><p>The standard trick: <code>echo</code> the text and pipe it into <code>sudo tee</code>, which writes the file as root.</p>",
        try: [`echo "nameserver ${p.newDns}" | sudo tee /etc/resolv.conf`], done: (st) => [p.newDns, "1.1.1.1", "8.8.8.8"].includes(st.dns),
        learned: `<p>The file now says <code>nameserver ${p.newDns}</code>. On many modern systems this file is generated by DHCP, netplan or systemd-resolved, so the lasting fix belongs in that config. Worth remembering when a fix "doesn't stick" after a reboot.</p>`
      },
      {
        title: "Verify, then retry the original problem",
        body: "<p>Always finish by re-running the thing that was broken, not just your own test.</p>",
        try: ["dig google.com", "sudo apt update"], done: (st, ev) => ev.has("nameOk") && ev.has("aptOk"),
        learned: "<p>Names resolve and <code>apt update</code> works. Ticket solved.</p>"
      }
    ],
    story: `Pinging 8.8.8.8 worked but pinging names failed, so I knew the network was fine and the problem was DNS. resolv.conf still pointed at ${p.oldDns}, which had been retired and didn't answer ping. I pointed the server at the new DNS server ${p.newDns}, verified with dig, and re-ran apt update to confirm the original problem was gone.`
  }),
};
